#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const wikiRoot = path.join(repoRoot, ".gitnexus", "wiki");
const outputPath = path.join(wikiRoot, "document-index.md");
const gitignorePath = path.join(repoRoot, ".gitnexus", ".gitignore");

const sharedArtifactGitignore = `*

# Share GitNexus navigation artifacts, but keep local databases and parser caches out
# of git. Re-run \`bun run gitnexus:analyze\` from the repository root to refresh
# these files.
!.gitignore
!run.cjs
!meta.json
!update-document-index.cjs
!wiki/
!wiki/**
`;

const ignoredDirs = new Set([
  ".git",
  ".gitnexus",
  ".gjc",
  ".opencode",
  ".worktrees",
  ".wt",
  "coverage",
  "dist",
  "dist-chrome",
  "dist-firefox",
  "node_modules",
  "target",
  "__pycache__",
]);

function shouldSkipDir(name) {
  return ignoredDirs.has(name);
}

function walkMarkdownFiles(root, relativeBase = ".") {
  const entries = fs
    .readdirSync(root, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name));
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(root, entry.name);
    const relativePath = path.posix.join(relativeBase, entry.name);

    if (entry.isDirectory()) {
      if (shouldSkipDir(entry.name)) continue;
      files.push(...walkMarkdownFiles(fullPath, relativePath));
      continue;
    }

    if (entry.isFile() && entry.name.endsWith(".md")) {
      files.push(relativePath);
    }
  }

  return files;
}

function readFirstHeading(relativePath) {
  const fullPath = path.join(repoRoot, relativePath);
  const content = fs.readFileSync(fullPath, "utf8");
  const heading = content
    .split(/\r?\n/)
    .map((line) => line.trim())
    .find((line) => line.startsWith("# "));
  return heading ? heading.replace(/^#\s+/, "").trim() : "";
}

function formatTableRows(files) {
  return files
    .map((file) => {
      const title = readFirstHeading(file).replace(/\|/g, "\\|");
      return `| \`${file}\` | ${title || "-"} |`;
    })
    .join("\n");
}

function listWikiArtifacts() {
  if (!fs.existsSync(wikiRoot)) return [];
  return walkMarkdownFiles(wikiRoot, ".gitnexus/wiki")
    .filter((file) => file !== ".gitnexus/wiki/document-index.md")
    .sort((a, b) => a.localeCompare(b));
}

const sourceDocs = walkMarkdownFiles(repoRoot);
const wikiDocs = listWikiArtifacts();

const body = `# GitNexus Document Index

This file is generated by \`.gitnexus/update-document-index.cjs\` and is intended to make the repository's Markdown documentation visible from the committed GitNexus artifacts.

## Source Documents (${sourceDocs.length})

| Path | Title |
| --- | --- |
${formatTableRows(sourceDocs)}

## GitNexus Wiki Artifacts (${wikiDocs.length})

${wikiDocs.map((file) => `- \`${file}\``).join("\n")}
`;

fs.writeFileSync(outputPath, body);
fs.writeFileSync(gitignorePath, sharedArtifactGitignore);
console.log(`wrote ${path.relative(repoRoot, outputPath)} (${sourceDocs.length} source docs, ${wikiDocs.length} wiki docs)`);
